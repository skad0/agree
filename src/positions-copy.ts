for (const locale of Object.keys(values) as Locale[]) {
  if (values[locale].length !== keys.length) throw new Error(`positions copy for ${locale} has ${values[locale].length} strings`);
}

export function pc(locale: Locale, key: PositionsKey): string {
  return values[locale][keys.indexOf(key)]!;
}

export function stanceLabel(locale: Locale, stance: PositionStance | "none"): string {
  switch (stance) {
    case "supports":
      return pc(locale, "stanceSupports");
    case "supports_with_reservations":
      return pc(locale, "stanceReservations");
    case "opposes":
      return pc(locale, "stanceOpposes");
    case "statement_available":
      return pc(locale, "stanceStatement");
    case "declined":
      return pc(locale, "stanceDeclined");
    case "none":
      return pc(locale, "stanceNone");
    default: {
      const _exhaustive: never = stance;
      return _exhaustive;
    }
  }
}

/** A glyph beside every label, so status never rests on colour alone. */
export function stanceMark(stance: PositionStance | "none"): string {
  switch (stance) {
    case "supports":
      return "✓";
    case "supports_with_reservations":
      return "◐";
    case "opposes":
      return "✕";
    case "statement_available":
      return "•";
    case "declined":
      return "?";
    case "none":
      return "–";
    default: {
      const _exhaustive: never = stance;
      return _exhaustive;
    }
  }
}
