for (const locale of Object.keys(values) as Locale[]) {
  if (values[locale].length !== keys.length) throw new Error(`Incomplete scorecard copy: ${locale}`);
}

export function sc(locale: Locale, key: ScorecardKey): string {
  return values[locale][keys.indexOf(key)]!;
}

export function statusLabel(locale: Locale, status: ComplianceStatus): string {
  switch (status) {
    case "PASS":
      return sc(locale, "statusPass");
    case "FAIL":
      return sc(locale, "statusFail");
    case "PARTIAL":
      return sc(locale, "statusPartial");
    case "UNCOMMITTED":
      return sc(locale, "statusUncommitted");
    default: {
      const _exhaustive: never = status;
      return _exhaustive;
    }
  }
}

export function blockLabel(locale: Locale, block: PartyBlock): string {
  switch (block) {
    case "coalition-37":
      return sc(locale, "blockCoalition");
    case "opposition":
      return sc(locale, "blockOpposition");
    case "arab":
      return sc(locale, "blockArab");
    default: {
      const _exhaustive: never = block;
      return _exhaustive;
    }
  }
}
